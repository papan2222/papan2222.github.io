"""Create smaller WebP previews; original images are never changed."""
import hashlib
import html
import json
import re
from pathlib import Path
from urllib.parse import unquote, urlsplit
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "assets" / "previews"
OUT.mkdir(parents=True, exist_ok=True)
HOST = "papan2222.github.io"
VERSION = b"preview-v1-640-1280-q80"
manifest_path = OUT / "manifest.json"
old = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {}
manifest = {}

def key_for(value, section=""):
    u = urlsplit(html.unescape(value))
    if u.netloc and u.netloc != HOST:
        return None
    if u.scheme and u.scheme not in ("http","https"):
        return None
    path = unquote(u.path)
    if not path:
        return None
    key = path.lstrip("/") if path.startswith("/") else (section+"/"+path).strip("/")
    if ".." in Path(key).parts:
        return None
    return key

def preview(key):
    if not key or key in manifest:
        return manifest.get(key)
    src = ROOT / key
    if src.suffix.lower() not in (".jpg",".jpeg",".png",".webp") or not src.is_file():
        return None
    data = src.read_bytes()
    digest = hashlib.sha256(VERSION + data).hexdigest()[:24]
    cached = old.get(key)
    if cached and cached.get("digest") == digest and all((ROOT/v["path"].lstrip("/")).is_file() for v in cached["variants"]):
        manifest[key] = cached
        return cached
    try:
        with Image.open(src) as opened:
            if getattr(opened,"is_animated",False):
                return None
            im = ImageOps.exif_transpose(opened)
            w,h = im.size
            if w < 400:
                return None
            im = im.convert("RGBA" if "A" in im.getbands() or "transparency" in im.info else "RGB")
            variants = []
            for target in (640,1280):
                if w < target and variants:
                    continue
                width = min(w,target)
                name = f"{digest}-{width}.webp"
                dest = OUT/name
                if not dest.exists():
                    thumb = im.copy()
                    thumb.thumbnail((width, max(1,round(h*width/w))),Image.Resampling.LANCZOS)
                    thumb.save(dest,"WEBP",quality=80,method=4)
                if dest.stat().st_size < len(data)*0.85:
                    variants.append({"path":"/assets/previews/"+name,"width":width,"bytes":dest.stat().st_size})
            if not variants:
                return None
            entry = {"digest":digest,"width":w,"height":h,"originalBytes":len(data),"variants":variants}
            manifest[key] = entry
            return entry
    except (OSError, ValueError) as exc:
        print("Skipped",key, str(exc))
        return None

def patch_static(path, section, sizes, first_eager=False):
    if not path.is_file():
        return
    source = path.read_text(encoding="utf-8")
    count = 0
    def replace(m):
        nonlocal count
        tag=m[0]
        src=re.search(r'\bsrc="([^"]+)"',tag)
        if not src:
            return tag
        # Only remove attributes generated by this script.
        tag=re.sub(r'\sdata-preview-auto="1"\s+srcset="[^"]*"\s+sizes="[^"]*"','',tag)
        entry=preview(key_for(src[1],section))
        count+=1
        if entry and not re.search(r'\bsrcset=',tag):
            variants=list(entry["variants"])
            # Preserve access to full resolution on wide/high-density screens.
            if entry["width"]>variants[-1]["width"]:
                variants.append({"path":"/"+key_for(src[1],section),"width":entry["width"]})
            srcset=", ".join(v["path"]+" "+str(v["width"])+"w" for v in variants)
            tag=tag[:-1]+f' data-preview-auto="1" srcset="{html.escape(srcset,quote=True)}" sizes="{sizes}">'
        if 'decoding=' not in tag:
            tag=tag[:-1]+' decoding="async">'
        if first_eager and count==1:
            tag=tag.replace('loading="lazy"','loading="eager"')
        return tag
    updated=re.sub(r'<img\b[^>]*>',replace,source)
    if updated!=source:
        path.write_text(updated,encoding="utf-8")

def main():
    for section,file,field in (("pandalife","works.json","images"),("game","gallery.json","file")):
        for work in json.loads((ROOT/section/file).read_text(encoding="utf-8")):
            values=work[field] if field=="images" else [work[field]]
            for value in values:
                preview(key_for(value,section))
    # Keep source galleries unchanged: generated work pages can be rebuilt safely.
    for section in ("pandalife","game","blog","senryu"):
        for path in (ROOT/section/"works").glob("*/index.html"):
            patch_static(path,section,"(max-width: 800px) 100vw, 800px",True)
    for path in (ROOT/"animalenglish/word").glob("*.html"):
        patch_static(path,"animalenglish/word","(max-width: 560px) 100vw, 560px",True)
    for path in (ROOT/"animalenglish/topics").glob("*/index.html"):
        patch_static(path,"animalenglish/topics","(max-width: 600px) 100vw, 360px")
    for section,file,sizes in (("blog","index.md","(max-width: 600px) 100vw, 400px"),("senryu","index.md","(max-width: 800px) 100vw, 800px"),("animalenglish","index.html","(max-width: 600px) 100vw, 360px")):
        # Source cards are copied by the SEO generator. Preview attributes use absolute URLs.
        patch_static(ROOT/section/file,section,sizes)
    patch_static(ROOT/"index.html","","230px",True)
    manifest_path.write_text(json.dumps(manifest,ensure_ascii=False,sort_keys=True,separators=(",",":")),encoding="utf-8")
    mapping={k:v["variants"] for k,v in manifest.items()}
    (OUT/"manifest.js").write_text("window.PandaPreviews="+json.dumps(mapping,ensure_ascii=True,separators=(",",":"))+";",encoding="utf-8")
    total=sum(v["originalBytes"] for v in manifest.values())
    small=sum(v["variants"][0]["bytes"] for v in manifest.values())
    report={"optimizedImages":len(manifest),"originalBytes":total,"smallPreviewBytes":small}
    (OUT/"report.json").write_text(json.dumps(report,indent=2),encoding="utf-8")
    print(report)
if __name__=="__main__":
    main()
